export function icon(name: string, size = 16, cls = ""): SVGElement {
  const node = ICONS[name] ?? ICONS.x;
  return createElement(node, {
    width: size,
    height: size,
    "stroke-width": size <= 14 ? 2 : 1.75,
    class: `i i-${name} ${cls}`.trim(),
  });
}

/** Replace all `<i data-icon="name" data-size="16">` placeholders. */
export function hydrateIcons(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("i[data-icon]")) {
    el.replaceWith(icon(el.dataset.icon ?? "x", Number(el.dataset.size ?? 16)));
  }
}
